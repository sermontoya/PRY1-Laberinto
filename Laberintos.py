"""
This function receives the number of rows and columns and create a matrix fill with 0s.
"""
def crearMatrizNula(filas, columnas):
    matriz=[]
    temp=[]
    i=0
    j=0
    while i<filas:
        while j<columnas:
            temp+=[0]
            j+=1
        matriz+=[temp]
        j=0
        i+=1
        temp=[]
    return matriz

"""
This function check that a maze already has a starting point (2 in the matrix).
"""
def tienePuntoInicio(matriz):
    for i in range(len(matriz)):
        for j in range(len(matriz)):
            if matriz[i][j]==2:
                return True
    return False

"""
This function create randomly a starting point in the maze with a 2.
"""
def marcarPuntoInicio(matriz):
    tamano=len(matriz)
    matrizTemp=copy.deepcopy(matriz)
    posX= random.randint(0, tamano-1)
    posY= random.randint(0, tamano-1)
    while matrizTemp[posX][posY]!=1 and matrizTemp[posX][posY]==3:
        posX= random.randint(0, tamano-1)
        posY= random.randint(0, tamano-1)
    matriz[posX][posY]=2
    return matriz

"""
This function remove the starting point in the maze, changing the 2 to 1.
"""
def desmarcarPuntoInicio(matriz):
    tamano=len(matriz)
    for i in range(tamano):
        for j in range(tamano):
            if matriz[i][j]==2:
                matriz[i][j]=1
    return matriz


