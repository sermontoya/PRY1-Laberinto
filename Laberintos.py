"""
This function receives a list of matrices and returns the best solution found, looking for the one with the fewest steps (4s in the matrix).
"""
def solucionOptima(listaMatrices):
    cantPasosMejorSolucion=cantCuatros(listaMatrices[0])
    mejorSolucion=listaMatrices[0]
    for matriz in listaMatrices:
        cantPasos=cantCuatros(matriz)
        if cantPasosMejorSolucion>cantPasos:
            cantPasosMejorSolucion=cantPasos
            mejorSolucion=matriz
    return mejorSolucion
        
"""
This function returns True if the finish is found around the square located at the coordinate (posX, posY).
"""
def comprobarMetaAlrededores(matriz, x, y):
    if comprobarPosicionValida(len(matriz), x-1, y) and matriz[x-1][y] == 3:
        return True
    elif comprobarPosicionValida(len(matriz), x+1, y) and matriz[x+1][y] == 3:
        return True
    elif comprobarPosicionValida(len(matriz), x, y-1) and matriz[x][y-1] == 3:
        return True
    elif comprobarPosicionValida(len(matriz), x, y+1) and matriz[x][y+1] == 3:
        return True
    return False

"""
This function returns the number of fours (4) in the array.
"""
def cantCuatros(matriz):
    resultado=0
    for i in matriz:
        for j in i:
            if j==4:
                resultado+=1
    return resultado

"""
This function receives the matrix and changes all 4 to 1, that is, it eliminates the steps performed.
"""
def limpiar(matriz):
    for i in range(len(matriz)):
        for j in range(len(matriz[0])):
            if matriz[i][j]==4:
                matriz[i][j]=1
    return matriz

"""
This function receives the matrix and returns the list of coordinates (steps) taken for the most optimal solution.
"""
def obtenerPasos(matriz):
    coordenada_inicio = [0, 0]
    coordenadas = []
    for i in range(len(matriz)):
        for j in range(len(matriz[0])):
            if matriz[i][j]==2:
                coordenada_inicio = [i, j]
    coordenadas.append(coordenada_inicio)
    n = 0
    encontrado = False
    while encontrado == False:
        
        arriba = 0
        abajo = 0
        derecha = 0
        izquierda = 0

        i = coordenada_inicio[0]
        j = coordenada_inicio[1]

        if i != 0:
            arriba = matriz[i-1][j]
        if i != len(matriz)-1:
            abajo = matriz[i+1][j]
        if j != 0:
            derecha = matriz[i][j-1]
        if j != len(matriz[0])-1:
            izquierda = matriz[i][j+1]

        if arriba == 3 or abajo == 3 or derecha == 3 or izquierda == 3 or n == 30:
            encontrado = True
        
        if arriba == 4:
            if [i-1, j] not in coordenadas:
                i-=1
                coordenada_inicio = [i, j]
                coordenadas.append([i, j])
                continue  
        if abajo == 4:
            if [i+1, j] not in coordenadas:
                i+=1
                coordenada_inicio = [i, j]
                coordenadas.append([i, j])
                continue  
        if derecha == 4:
            if [i, j-1] not in coordenadas:
                j-=1
                coordenada_inicio = [i, j]
                coordenadas.append([i, j])
                continue  
        if izquierda == 4:
            if [i, j+1] not in coordenadas:
                j+=1
                coordenada_inicio = [i, j]
                coordenadas.append([i, j])
                continue  

    return coordenadas
